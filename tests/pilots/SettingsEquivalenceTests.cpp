// Core/SettingsFile.hpp against train-simulator's Config::Settings, compiled
// read-only: the same files must read as the same values, and the same values
// must be written as the same bytes. Left out when train-simulator is not
// checked out beside this repository.
#include "CnaEngine/Core/SettingsFile.hpp"

#include "trainsim/config/Settings.hpp"

#include <gtest/gtest.h>

#include <filesystem>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

namespace
{
    using CnaEngine::SettingsFile;
    using TrainSim::Config::Settings;

    // train-simulator's keys, ranges and defaults (Settings.hpp/.cpp), read through the engine.
    Settings Read(const SettingsFile& file)
    {
        const Settings defaults;
        Settings settings;
        settings.mouseSensitivity = file.GetFloat("mouse_sensitivity", defaults.mouseSensitivity, 0.0005f, 0.010f);
        settings.masterVolume = file.GetFloat("master_volume", defaults.masterVolume, 0.0f, 1.0f);
        settings.announcementVolume = file.GetFloat("announcement_volume", defaults.announcementVolume, 0.0f, 1.0f);
        settings.passengerVolume = file.GetFloat("passenger_volume", defaults.passengerVolume, 0.0f, 1.0f);
        settings.trainVolume = file.GetFloat("train_volume", defaults.trainVolume, 0.0f, 1.0f);
        settings.cameraVibration = file.GetFloat("camera_vibration", defaults.cameraVibration, 0.0f, 1.0f);
        settings.fieldOfViewDegrees = file.GetFloat("field_of_view_degrees", defaults.fieldOfViewDegrees, 55.0f, 100.0f);
        settings.graphicsQuality = file.GetInt("graphics_quality", defaults.graphicsQuality, 0, 2);
        settings.vegetationDistanceMetres =
            file.GetFloat("vegetation_distance_metres", defaults.vegetationDistanceMetres, 250.0f, 1000.0f);
        settings.announcementCaptions = file.GetBool("announcement_captions", defaults.announcementCaptions);
        settings.serviceStartMinutes = file.GetInt("service_start_minutes", defaults.serviceStartMinutes, 0, 1439);
        settings.weatherMode = file.GetInt("weather", defaults.weatherMode, 0, 5);
        return settings;
    }

    SettingsFile Write(const Settings& settings)
    {
        SettingsFile file;
        file.SetHeader("User preferences generated by Train Simulator.");
        file.SetFloat("mouse_sensitivity", settings.mouseSensitivity);
        file.SetFloat("master_volume", settings.masterVolume);
        file.SetFloat("announcement_volume", settings.announcementVolume);
        file.SetFloat("passenger_volume", settings.passengerVolume);
        file.SetFloat("train_volume", settings.trainVolume);
        file.SetFloat("camera_vibration", settings.cameraVibration);
        file.SetFloat("field_of_view_degrees", settings.fieldOfViewDegrees);
        file.SetInt("graphics_quality", settings.graphicsQuality);
        file.SetFloat("vegetation_distance_metres", settings.vegetationDistanceMetres);
        file.SetBool("announcement_captions", settings.announcementCaptions);
        file.SetInt("service_start_minutes", settings.serviceStartMinutes);
        file.SetInt("weather", settings.weatherMode);
        return file;
    }

    void ExpectSame(const Settings& engine, const Settings& train, const std::string& text)
    {
        EXPECT_EQ(engine.mouseSensitivity, train.mouseSensitivity) << text;
        EXPECT_EQ(engine.masterVolume, train.masterVolume) << text;
        EXPECT_EQ(engine.announcementVolume, train.announcementVolume) << text;
        EXPECT_EQ(engine.passengerVolume, train.passengerVolume) << text;
        EXPECT_EQ(engine.trainVolume, train.trainVolume) << text;
        EXPECT_EQ(engine.cameraVibration, train.cameraVibration) << text;
        EXPECT_EQ(engine.fieldOfViewDegrees, train.fieldOfViewDegrees) << text;
        EXPECT_EQ(engine.graphicsQuality, train.graphicsQuality) << text;
        EXPECT_EQ(engine.vegetationDistanceMetres, train.vegetationDistanceMetres) << text;
        EXPECT_EQ(engine.announcementCaptions, train.announcementCaptions) << text;
        EXPECT_EQ(engine.serviceStartMinutes, train.serviceStartMinutes) << text;
        EXPECT_EQ(engine.weatherMode, train.weatherMode) << text;
    }

    std::string Contents(const std::filesystem::path& path)
    {
        std::ifstream input(path);
        std::ostringstream text;
        text << input.rdbuf();
        return text.str();
    }
}

TEST(SettingsEquivalenceTests, TrainSimulatorFilesReadTheSame)
{
    Settings changed;
    changed.mouseSensitivity = 0.0031f;
    changed.masterVolume = 0.25f;
    changed.graphicsQuality = 0;
    changed.announcementCaptions = false;
    changed.serviceStartMinutes = 21 * 60 + 45;
    changed.weatherMode = 3;
    const std::vector<std::string> texts{
        "",
        Settings{}.serialize(),
        changed.serialize(),
        "# hand edited\n  master_volume=1.7   # too loud\r\nfield_of_view_degrees = 20\n"
        "graphics_quality = 2.6\nweather = -4\nannouncement_captions = 0.49\n"
        "service_start_minutes = 1439.6\nmouse_sensitivity = 0.003\nmaster_volume = 0.5\n",
        "vegetation_distance_metres = 5000\ncamera_vibration = 0\ntrain_volume=0.0001\n",
    };
    for (const std::string& text : texts) {
        const SettingsFile file = SettingsFile::Parse(text);
        EXPECT_TRUE(file.Problems().empty()) << text;
        ExpectSame(Read(file), Settings::parse(text), text);
    }
}

TEST(SettingsEquivalenceTests, TrainSimulatorFilesWriteTheSameBytes)
{
    const auto scratch = std::filesystem::current_path() / "cna_engine_settings_probe";
    std::filesystem::remove_all(scratch);
    Settings odd;
    odd.mouseSensitivity = 0.00071f;
    odd.passengerVolume = 1.0f / 3.0f;
    odd.fieldOfViewDegrees = 72.5f;
    odd.vegetationDistanceMetres = 333.33333f;
    for (const Settings& settings : {Settings{}, odd}) {
        EXPECT_EQ(Write(settings).Serialize(), settings.serialize());
        settings.save(scratch / "train" / "train-simulator.cfg");
        Write(settings).Save(scratch / "engine" / "train-simulator.cfg");
        EXPECT_EQ(Contents(scratch / "engine" / "train-simulator.cfg"),
                  Contents(scratch / "train" / "train-simulator.cfg"));
        ExpectSame(Read(SettingsFile::Load(scratch / "engine" / "train-simulator.cfg")),
                   Settings::load(scratch / "train" / "train-simulator.cfg"), "saved");
    }
    std::filesystem::remove_all(scratch);
}
